/**
 * 清单列表容器类 —— **两端共用同一个值**（设计文档 §8.3：手机与 PC 共享原子件，
 * 只改「排列方式」）。手机上 `grid-cols-1` 就是单列卡片，PC 从 `lg`(1024px) 起自动变双列。
 *
 * ## 为什么两端不再各写一份
 *
 * 2026-09-11 用户反馈「移动端的清单 card 没有外框」：当时手机上走的是"整行 + 极细分隔线"
 * （无边框、透明底），而 PC 上是带外框的卡片，同一个页面里一键日常入口卡又是带框的 ——
 * 同一屏出现两种形态，看起来像没画完。两端统一成同一张卡后，差异只剩列数。
 *
 * ## 双列断点为什么是 `lg`
 *
 * 内容区上限 `max-w-5xl`(1024px)、左侧栏固定 224px，所以 1024px 视口下内容区约 800px，
 * 双列每列约 390px —— 装得下「名称 + 徽章 + 两行说明」。
 * 原先写的 `xl`(1280px) 会让 **1024–1280px 这段最常见的笔记本宽度退化成单列**，
 * 一整行只放一张卡、右侧一大片留白。
 * 不放到 `md`(768px)：内容区会窄到约 540px，双列每列 265px，徽章与说明会挤成三行。
 *
 * ## 水平内缩 14px（`px-3.5`）
 *
 * 与 `SectionTitle`、卡片内部 padding 同一口径，所以分区标题的左边界正好对齐卡片外框。
 * 曾经栅格是 12px、标题是 14px，差 2px —— 这种"说不上哪里脏"的错位最难查。
 */
export const CHECKLIST_GRID = 'grid grid-cols-1 gap-2 px-3.5 py-2 lg:grid-cols-2';
